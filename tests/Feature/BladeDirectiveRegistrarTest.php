    /**
     * Every canonical and Spatie-compat directive registers a matching
     * `@endunless<name>` alias — a migrated Spatie view that uses
     * `@endunlesshasrole`, `@endunlesshasanyrole`, `@endunlesshasallroles`,
     * `@endunlesspermission`, `@endunlessanypermission`,
     * `@endunlessallpermissions`, `@endunlesshaspermission`,
     * `@endunlesshasanypermission`, or `@endunlesshasallpermissions` compiles
     * cleanly alongside `@endunlessrole`.
     *
     * @return void
     */
    public function testEveryUnlessVariantHasASpatieShapedClosingAlias(): void
    {
        Role::create(['id' => (string) Str::uuid(), 'name' => 'admin', 'guard' => 'web']);
        Permission::create(['id' => (string) Str::uuid(), 'name' => 'posts:draft', 'guard' => 'web']);

        $user = StubIdentity::create(['id' => (string) Str::uuid()]);
        $this->actAs($user);

        $closings = [
            '@unlessrole(\'admin\') yes @endunlessrole',
            '@unlessanyrole([\'admin\']) yes @endunlessanyrole',
            '@unlessallroles([\'admin\']) yes @endunlessallroles',
            '@unlesshasrole(\'admin\') yes @endunlesshasrole',
            '@unlesshasanyrole([\'admin\']) yes @endunlesshasanyrole',
            '@unlesshasallroles([\'admin\']) yes @endunlesshasallroles',
            '@unlesspermission(\'posts:draft\') yes @endunlesspermission',
            '@unlessanypermission([\'posts:draft\']) yes @endunlessanypermission',
            '@unlessallpermissions([\'posts:draft\']) yes @endunlessallpermissions',
            '@unlesshaspermission(\'posts:draft\') yes @endunlesshaspermission',
            '@unlesshasanypermission([\'posts:draft\']) yes @endunlesshasanypermission',
            '@unlesshasallpermissions([\'posts:draft\']) yes @endunlesshasallpermissions',
        ];

        foreach ($closings as $template) {
            self::assertSame('yes', $this->render($template), "Failed template: {$template}");
        }
    }

    /**
     * `@hasrole`, `@hasanyrole`, `@hasallroles` are Spatie-compat aliases —
     * they must behave identically to their canonical counterparts so a
     * migrated view renders unchanged.
     *
     * @return void
     */
    public function testSpatieAliasesMatchCanonicalBehaviour(): void
    {
        Role::create(['id' => (string) Str::uuid(), 'name' => 'admin', 'guard' => 'web']);
        Role::create(['id' => (string) Str::uuid(), 'name' => 'editor', 'guard' => 'web']);

        $user = StubIdentity::create(['id' => (string) Str::uuid()]);
        $user->assignRole('admin');

        $this->actAs($user);

        self::assertSame('yes', $this->render('@hasrole(\'admin\') yes @endhasrole'));
        self::assertSame('yes', $this->render('@hasanyrole([\'editor\', \'admin\']) yes @endhasanyrole'));
        self::assertSame('', $this->render('@hasallroles([\'admin\', \'editor\']) yes @endhasallroles'));

        $user->assignRole('editor');
        self::assertSame('yes', $this->render('@hasallroles([\'admin\', \'editor\']) yes @endhasallroles'));
    }

    /**
     * `@haspermission`, `@hasanypermission`, `@hasallpermissions` are the
     * permission-side Spatie-compat aliases — they must behave identically to
     * their canonical counterparts so a migrated view renders unchanged.
     *
     * @return void
     */
    public function testSpatiePermissionAliasesMatchCanonicalBehaviour(): void
    {
        Permission::create(['id' => (string) Str::uuid(), 'name' => self::PERMISSION, 'guard' => 'web']);
        Permission::create(['id' => (string) Str::uuid(), 'name' => 'posts:delete', 'guard' => 'web']);

        $user = StubIdentity::create(['id' => (string) Str::uuid()]);
        $user->givePermission(self::PERMISSION);

        $this->actAs($user);

        self::assertSame('yes', $this->render('@haspermission(\'' . self::PERMISSION . '\') yes @endhaspermission'));
        self::assertSame('yes', $this->render('@hasanypermission([\'posts:delete\', \'' . self::PERMISSION . '\']) yes @endhasanypermission'));
        self::assertSame('', $this->render('@hasallpermissions([\'' . self::PERMISSION . '\', \'posts:delete\']) yes @endhasallpermissions'));

        $user->givePermission('posts:delete');
        self::assertSame('yes', $this->render('@hasallpermissions([\'' . self::PERMISSION . '\', \'posts:delete\']) yes @endhasallpermissions'));
    }

    /**
     * `@unlesshaspermission` / `@unlesshasanypermission` /
     * `@unlesshasallpermissions` close with the Spatie-shaped
     * `@endunless<name>` directives. Anonymous principal evaluates every
     * predicate to false so the unless-bodies render.
     *
     * @return void
     */
    public function testSpatiePermissionUnlessAliasesCompileWithEndunless(): void
    {
        Permission::create(['id' => (string) Str::uuid(), 'name' => 'posts:draft', 'guard' => 'web']);

        $user = StubIdentity::create(['id' => (string) Str::uuid()]);
        $this->actAs($user);

        self::assertSame('yes', $this->render('@unlesshaspermission(\'posts:draft\') yes @endunlesshaspermission'));
        self::assertSame('yes', $this->render('@unlesshasanypermission([\'posts:draft\']) yes @endunlesshasanypermission'));
        self::assertSame('yes', $this->render('@unlesshasallpermissions([\'posts:draft\']) yes @endunlesshasallpermissions'));
    }

    /**
     * Empty-string arguments must never admit the block — an accidental
     * `@role('')` or typo-driven `@permission('')` is rejected at the helper
     * rather than treated as "match everything".
     *
     * @return void
     */
    public function testEmptyStringArgumentDoesNotAdmit(): void
    {
        $user = StubIdentity::create(['id' => (string) Str::uuid()]);

        $this->actAs($user);

        self::assertSame('', $this->render('@role(\'\') admitted @endrole'));
        self::assertSame('', $this->render('@permission(\'\') admitted @endpermission'));
    }

    /**
     * Every directive splits `|` lists, the any directives admitting on one
     * held name, the all directives requiring each.
     *
     * @return void
     */
    public function testEveryDirectiveSplitsPipeLists(): void
    {
        $this->actAs(self::identityHolding(['admin', 'editor'], [self::PERMISSION, 'posts:delete']));

        foreach (['role', 'anyrole', 'hasrole', 'hasanyrole'] as $name) {
            self::assertSame('yes', $this->render("@{$name}('auditor|admin') yes @end{$name}"), "@{$name} did not split.");
        }

        foreach (['allroles', 'hasallroles'] as $name) {
            self::assertSame('yes', $this->render("@{$name}('admin | editor') yes @end{$name}"), "@{$name} did not split.");
            self::assertSame('', $this->render("@{$name}('admin|auditor') yes @end{$name}"), "@{$name} admitted a partial list.");
        }

        foreach (['permission', 'anypermission', 'haspermission', 'hasanypermission'] as $name) {
            self::assertSame('yes', $this->render("@{$name}('posts:publish|posts:delete') yes @end{$name}"), "@{$name} did not split.");
        }

        foreach (['allpermissions', 'hasallpermissions'] as $name) {
            self::assertSame('yes', $this->render("@{$name}('" . self::PERMISSION . "|posts:delete') yes @end{$name}"), "@{$name} did not split.");
            self::assertSame('', $this->render("@{$name}('" . self::PERMISSION . "|posts:publish') yes @end{$name}"), "@{$name} admitted a partial list.");
        }
    }

    /**
     * The permission directives decide on the full decision: an explicit deny
     * wins over a held permission, and a policy allow admits without one.
     *
     * @return void
     */
    public function testPermissionDirectivesDecideOnTheFullDecision(): void
    {
        $identity = self::identityHolding(permissions: [self::PERMISSION]);
        self::attachStatement($identity, 'deny', [self::PERMISSION]);
        self::attachStatement($identity, 'allow', ['posts:publish']);

        $this->actAs($identity);

        self::assertSame('', $this->render('@permission(\'' . self::PERMISSION . '\') yes @endpermission'));
        self::assertSame('yes', $this->render('@allpermissions(\'posts:publish\') yes @endallpermissions'));
    }

    /**
     * Every role directive passes its guard on: only roles of that guard or of
     * no guard count.
     *
     * @return void
     */
    public function testRoleDirectivesHonourAGuard(): void
    {
        config(['auth.guards.api' => ['driver' => 'session', 'provider' => 'users']]);

        $identity = StubIdentity::create(['id' => (string) Str::uuid()]);
        $identity->assignRole(Role::create(['name' => 'admin', 'guard' => 'api']));

        $this->actAs($identity);

        foreach (['role', 'anyrole', 'allroles', 'hasrole', 'hasanyrole', 'hasallroles'] as $name) {
            self::assertSame('yes', $this->render("@{$name}('admin', 'api') yes @end{$name}"), "@{$name} dropped the guard.");
            self::assertSame('', $this->render("@{$name}('admin', 'web') yes @end{$name}"), "@{$name} ignored the guard.");
        }
    }

    /**
     * Every permission directive refuses a guard rather than dropping it.
     *
     * @return void
     */
    public function testPermissionDirectivesRefuseAGuard(): void
    {
        $this->actAs(self::identityHolding(permissions: [self::PERMISSION]));

        foreach (['permission', 'anypermission', 'allpermissions', 'haspermission', 'hasanypermission', 'hasallpermissions'] as $name) {
            try {
                $this->render("@{$name}('" . self::PERMISSION . "', 'web') yes @end{$name}");
                self::fail("@{$name} dropped the guard.");
            } catch (\Throwable $exception) {
                self::assertInstanceOf(InvalidCheckArgumentException::class, $exception->getPrevious() ?? $exception, "@{$name} did not refuse the guard.");
            }
        }
    }

    /**
     * Render a template and strip surrounding whitespace so the assertions read
     * cleanly.
     *
     * @param  string  $template
     * @return string
     */
    private function render(string $template): string
    {
        return \trim(Blade::render($template));
    }
}
